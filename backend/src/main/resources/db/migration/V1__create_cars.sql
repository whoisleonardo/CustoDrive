CREATE TABLE cars (
    id BIGSERIAL PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    brand VARCHAR(80),
    model VARCHAR(120),
    version VARCHAR(120),
    model_year INTEGER,
    vin VARCHAR(32),
    purchase_price NUMERIC(14, 2) NOT NULL CHECK (purchase_price >= 0),
    initial_costs NUMERIC(14, 2) NOT NULL CHECK (initial_costs >= 0),
    ipva_rate_percent NUMERIC(6, 2) NOT NULL CHECK (ipva_rate_percent >= 0),
    annual_insurance NUMERIC(14, 2) NOT NULL CHECK (annual_insurance >= 0),
    annual_maintenance NUMERIC(14, 2) NOT NULL CHECK (annual_maintenance >= 0),
    consumption_per100 NUMERIC(10, 2) NOT NULL CHECK (consumption_per100 >= 0),
    energy_unit_price NUMERIC(10, 2) NOT NULL CHECK (energy_unit_price >= 0),
    monthly_km NUMERIC(10, 2) NOT NULL CHECK (monthly_km >= 0),
    monthly_parking NUMERIC(14, 2) NOT NULL CHECK (monthly_parking >= 0),
    monthly_other_costs NUMERIC(14, 2) NOT NULL CHECK (monthly_other_costs >= 0),
    body_class VARCHAR(100),
    fuel_type VARCHAR(100),
    drive_type VARCHAR(100),
    transmission VARCHAR(100),
    doors INTEGER,
    seats INTEGER,
    length_mm NUMERIC(10, 2),
    width_mm NUMERIC(10, 2),
    height_mm NUMERIC(10, 2),
    wheelbase_mm NUMERIC(10, 2),
    curb_weight_kg NUMERIC(10, 2),
    battery_kwh NUMERIC(10, 2),
    electrification_level VARCHAR(100),
    specs_source VARCHAR(80),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_cars_name ON cars (name);
